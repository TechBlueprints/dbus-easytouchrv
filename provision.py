"""
EasyTouch RV Provisioning Tool

Scans BLE for EasyTouch RV controllers and generates a ready-to-use config.ini
for dbus-easytouchrv.  EasyTouch controllers advertise a recognizable BLE name,
so no cloud account is required to discover them.

Usage:
    python3 provision.py [--output PATH] [--timeout SECONDS] [--passcode PASS]
"""

import argparse
import asyncio
import configparser
import os
import re
import sys

# Make the bundled BLE stack importable when run from the repo.
_ext = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ext")
for _sub in [
    os.path.join(_ext, "bleak-connection-manager", "src"),
    os.path.join(_ext, "bleak-retry-connector", "src"),
    os.path.join(_ext, "bluetooth-adapters", "src"),
    os.path.join(_ext, "aiooui", "src"),
    os.path.join(_ext, "bleak"),
]:
    if os.path.isdir(_sub) and _sub not in sys.path:
        sys.path.insert(0, _sub)

# Installed before easytouch_ble captures bleak's classes at import time.
# On non-Linux hosts the catcher's claims/mgmt layers degrade to no-ops.
from bleak_connection_manager import install_bleak_catcher  # noqa: E402

install_bleak_catcher("easytouch-provision", wrap_scanner=True)

from easytouch_ble import scan_for_thermostats  # noqa: E402


def _section_name(name: str, mac: str) -> str:
    base = re.sub(r"[^a-zA-Z0-9_-]", "_", name).strip("_") or "Thermostat"
    return "%s_%s" % (base, mac.replace(":", "")[-4:])


def generate_config(devices, output_path: str, passcode: str):
    cfg = configparser.ConfigParser()
    cfg["DEFAULT"] = {
        "poll_interval_minutes": "5",
        "passcode": passcode,
    }

    for dev in devices:
        section = _section_name(dev.name, dev.mac)
        cfg[section] = {
            "name": dev.name,
            "mac": dev.mac,
            "zone": "0",
            "serial": dev.serial,
            "passcode": "",
        }

    with open(output_path, "w") as f:
        f.write("# EasyTouch RV Thermostat Configuration\n")
        f.write("# Generated by provision.py\n")
        f.write("#\n")
        f.write("# 'mac' is the BLE advertisement MAC address.\n")
        f.write("#\n\n")
        cfg.write(f)

    print("  Written to %s" % output_path)


async def run(args):
    print("=" * 50)
    print("  EasyTouch RV Provisioning Tool")
    print("=" * 50)
    print("\nScanning for EasyTouch controllers (%.0fs)..." % args.timeout)

    devices = await scan_for_thermostats(timeout=args.timeout)
    if not devices:
        print("  No EasyTouch devices found.")
        print("  Ensure the thermostat is powered and in BLE range.")
        return 1

    print("  Found %d device(s):" % len(devices))
    for dev in devices:
        print("    - %s" % dev.name)
        print("      MAC: %s  serial: %s  RSSI: %d" % (dev.mac, dev.serial, dev.rssi))

    print("\nWriting %s..." % args.output)
    generate_config(devices, args.output, args.passcode)

    print("\n" + "=" * 50)
    print("  Done! Review %s, then copy it to your Cerbo GX:" % args.output)
    print("    scp %s root@<cerbo>:/data/apps/dbus-easytouchrv/config.ini" % args.output)
    print("=" * 50)
    return 0


def main():
    parser = argparse.ArgumentParser(description="EasyTouch RV Provisioning")
    parser.add_argument("--output", default="config.ini",
                        help="Output config file (default: config.ini)")
    parser.add_argument("--timeout", type=float, default=15.0,
                        help="BLE scan duration in seconds (default: 15)")
    parser.add_argument("--passcode", default="",
                        help="Default passcode to write into the config")
    args = parser.parse_args()
    return asyncio.run(run(args))


if __name__ == "__main__":
    sys.exit(main())
